set -euo pipefail

nap_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
nap_mode="${1:-release}"
if [[ "$nap_mode" != release && "$nap_mode" != debug ]]; then
    echo "usage: bash build.sh [release|debug]" >&2
    exit 2
fi
nap_target="${NAP_STARK_TARGET_DIR:-$nap_root/target}"
nap_args=(build --locked --manifest-path "$nap_root/Cargo.toml" --features native-privacy --target-dir "$nap_target")
if [[ "$nap_mode" == release ]]; then
    nap_args+=(--release)
fi
cd -- "$nap_root"
cargo "${nap_args[@]}"
nap_archive="$nap_target/$nap_mode/libalgorand_asset_privacy_ffi.a"
if [[ -n "${CARGO_BUILD_TARGET:-}" ]]; then
    nap_archive="$nap_target/$CARGO_BUILD_TARGET/$nap_mode/libalgorand_asset_privacy_ffi.a"
fi
mkdir -p -- "$nap_root/lib"
cp -- "$nap_archive" "$nap_root/lib/libalgorand_asset_privacy_ffi.a"
# Go does not track changes to an external static archive in its package cache.
if command -v sha512sum >/dev/null 2>&1; then
    nap_digest="$(sha512sum "$nap_archive")"
else
    nap_digest="$(shasum -a 512 "$nap_archive")"
fi
nap_digest="${nap_digest%% *}"
if [[ ! "$nap_digest" =~ ^[0-9a-f]{128}$ ]]; then
    echo "invalid archive digest" >&2
    exit 2
fi
printf '%s\n' \
    '//go:build algorand_native_privacy && algorand_native_privacy_stark && cgo && (linux || darwin)' \
    '' \
    '// Code generated by stark-ffi/build.sh; DO NOT EDIT.' \
    'package proofbridge' \
    '' \
    "const backendArchiveDigest = \"$nap_digest\"" \
    > "$nap_root/../proofbridge/backend_archive_generated.go"
